-- 008: 订单未读标记 + 内部申请驳回原因
-- 可直接在 Navicat 查询窗口中运行
--
-- 说明：
-- 1. user_unread   用户侧未读标记（状态变更/报价/进度更新后通知用户）
-- 2. admin_unread  管理员侧未读标记（新订单到达/用户确认后通知管理员）
-- 3. reject_reason 内部申请驳回或订单取消原因

-- ============================================
-- 1. 用户未读标记
-- ============================================
ALTER TABLE orders
  ADD COLUMN `user_unread` TINYINT(1) NULL DEFAULT 0 COMMENT '用户未读标记: 1-有更新未查看, 0-已读';

-- ============================================
-- 2. 管理员未读标记
-- ============================================
ALTER TABLE orders
  ADD COLUMN `admin_unread` TINYINT(1) NULL DEFAULT 0 COMMENT '管理员未读标记: 1-有更新未查看, 0-已读';

-- ============================================
-- 3. 驳回/取消原因
-- ============================================
ALTER TABLE orders
  ADD COLUMN `reject_reason` VARCHAR(255) NULL COMMENT '内部申请驳回或订单取消原因';

-- ============================================
-- 完成
-- ============================================
SELECT '迁移 008 执行完成（未读标记 + 驳回原因）' AS result;
